"""Build a self-contained HTML from the maintainable browser sources.

Usage: python scripts/build_standalone.py [--output path/to/hit-clicker.html]
Uses only the Python standard library; does not change source files.
"""

import argparse
import base64
import json
import mimetypes
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def local_file(path, parent=ROOT):
    target = (parent / path).resolve()
    if not target.is_relative_to(ROOT) or not target.is_file():
        raise ValueError(f"Missing or non-project resource: {path}")
    return target


def data_url(path):
    mime = {
        ".svg": "image/svg+xml",
        ".ttf": "font/ttf",
        ".woff2": "font/woff2",
    }.get(path.suffix, mimetypes.guess_type(path.name)[0])
    if not mime:
        raise ValueError(f"Unknown resource type: {path}")
    encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{encoded}"


def build():
    html = (ROOT / "index.html").read_text(encoding="utf-8")
    # Dynamic image paths are resolved against this embedded map. They never
    # fall back to the filesystem or network, so new unbundled paths fail loudly.
    images = {
        path.relative_to(ROOT).as_posix(): data_url(path)
        for path in sorted((ROOT / "assets/figma").glob("*.svg"))
    }

    def inline_image(match):
        return match[1] + data_url(local_file(match[2])) + match[3]

    html = re.sub(r'(<img\b[^>]*\bsrc=")([^\"]+)(")', inline_image, html)

    def inline_style(match):
        href = re.search(r'href="([^\"]+)"', match[0])
        if not href:
            raise ValueError("Stylesheet link has no href")
        path = local_file(href[1])
        css = path.read_text(encoding="utf-8")

        def css_resource(resource):
            target = resource[1].strip().strip("\"'")
            if target.startswith(("#", "data:")):
                return resource[0]
            return 'url("' + data_url(local_file(target, path.parent)) + '")'

        css = re.sub(r"url\(([^)]+)\)", css_resource, css)
        return f'<style data-source="{href[1]}">\n{css}\n</style>'

    html = re.sub(r'<link\b[^>]*\brel="stylesheet"[^>]*>', inline_style, html)

    def inline_script(match):
        attrs = match[1]
        if "data-figma-capture" in attrs:
            return ""  # Editor integration is not part of the playable export.
        source = re.search(r'src="([^\"]+)"', attrs)
        if not source:
            return match[0]
        code = local_file(source[1]).read_text(encoding="utf-8")
        # Existing image assignments include static, template and ternary paths.
        # Map each result after evaluation; preserve all gameplay code and order.
        code = re.sub(
            r"(\b[\w.]+\.src\s*=\s*)([^;]+);",
            lambda assignment: assignment[1]
            + "window.HitEmbeddedAsset("
            + assignment[2].strip()
            + ");",
            code,
        )
        code = re.sub(r"</script", r"<\/script", code, flags=re.IGNORECASE)
        return f'<script data-source="{source[1]}">\n{code}\n</script>'

    html = re.sub(r"[ \t]*<script\b([^>]*)>\s*</script>", inline_script, html)
    asset_map = json.dumps(images, ensure_ascii=True, separators=(",", ":"))
    bootstrap = (
        "<script>\n// Generated resource map for this standalone export.\n"
        "window.HitEmbeddedAsset = (() => {\nconst images = " + asset_map + ";\n"
        "return path => { if (!Object.hasOwn(images, path)) "
        "throw new Error('Unbundled image: ' + path); return images[path]; };\n})();\n"
        "</script>\n"
    )
    html = html.replace("</head>", bootstrap + "</head>", 1)
    html = html.replace(
        "<!doctype html>",
        "<!doctype html>\n<!-- Generated by scripts/build_standalone.py. "
        "Edit the development sources, then rebuild. Font licenses and credits "
        "are embedded in the attribution JSON block. -->",
        1,
    )
    # A single-file download should also carry attribution and the font licenses.
    credits = (ROOT / "CREDITS.md").read_text(encoding="utf-8")
    licenses = dict(
        (path.name, path.read_text(encoding="utf-8"))
        for path in sorted((ROOT / "assets/fonts").glob("OFL-*.txt"))
    )
    # Avoid relative development-document links in the redistributed artifact.
    credits = credits.replace(
        "see docs/FIGMA_WORKFLOW.md for synchronization.",
        "see https://github.com/Chubeiliang233/hit-clicker/tree/development "
        "for design and development documentation.",
    )
    attribution = json.dumps(
        {"credits": credits, "font_licenses": licenses}, ensure_ascii=False, indent=2
    ).replace("<", "\\u003c")
    html = html.replace(
        "</body>",
        '<script id="hit-attribution" type="application/json">\n'
        + attribution + "\n</script>\n</body>",
        1,
    )
    if re.search(r'<(?:script|img)\b[^>]*\bsrc="(?!data:)', html):
        raise ValueError("Export still contains an external script or image")
    if re.search(r'<link\b[^>]*\brel="stylesheet"', html):
        raise ValueError("Export still contains an external stylesheet")
    return html


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "hit-clicker.html")
    args = parser.parse_args()
    output = args.output.resolve()
    if output.suffix.lower() != ".html":
        parser.error("Output must be an HTML file")
    if output == ROOT / "index.html":
        parser.error("Output must not overwrite the source index.html")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build(), encoding="utf-8", newline="\n")
    print(f"Built {output.name}: {output.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
